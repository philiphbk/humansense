"""
Render benchmarks/results/*.json into Markdown tables for paper/REPORT.md.

    python benchmarks/make_tables.py                 # writes paper/tables.md
    python benchmarks/make_tables.py --out -          # print to stdout instead

Known result shapes (latency_*, falls_*, ros2_e2e) get a purpose-built table; anything else falls
back to a generic flattened key/value table so a new benchmark's numbers are never silently
dropped, just less nicely formatted until this script learns its shape.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from common import HERE, RESULTS  # noqa: E402


def _row(*cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def _ms(d, key="median"):
    return f"{d[key]:.1f}" if d and key in d else "n/a"


def table_latency(data: dict) -> str:
    lines = [f"**{data['benchmark']}** -- backend `{data['backend']}`, source `{data['source']}`, "
             f"best of {data['repeats']} runs. {data['environment']['platform']}, "
             f"{data['environment']['cpu']}.", "",
             _row("Config", "Modules", "Frames", "Median ms", "p95 ms", "p99 ms", "Max ms"),
             _row(*["---"] * 7)]
    for name, cfg in data["configs"].items():
        t = cfg["total_ms"]
        lines.append(_row(name, ", ".join(cfg["modules"]), cfg["n_frames"],
                          f"{t['median']:.1f}", f"{t['p95']:.1f}", f"{t['p99']:.1f}", f"{t['max']:.1f}"))
    lines.append("")
    lines.append("Per-module breakdown (median ms):")
    lines.append("")
    mod_names = sorted({m for cfg in data["configs"].values() for m in cfg["per_module_ms"] if m != "total"})
    lines.append(_row("Config", *mod_names))
    lines.append(_row(*["---"] * (1 + len(mod_names))))
    for name, cfg in data["configs"].items():
        lines.append(_row(name, *[_ms(cfg["per_module_ms"].get(m)) for m in mod_names]))
    return "\n".join(lines)


def table_falls(data: dict) -> str:
    split = data.get("parity_split")
    title = f"**{data['benchmark']}** -- backend `{data['backend']}`"
    title += f", evaluated on {split}-numbered sequences only" if split else ""
    seqs = data["n_sequences"]
    lines = [title + f". {seqs['fall']} fall + {seqs['adl_lying']} ADL-lying + "
             f"{seqs['adl_plain']} ADL-plain sequences, {data['n_frames']} frames.", "",
             _row("Alarm", "Sensitivity", "FA / ADL-plain", "FA / ADL-lying", "Median delay (s)"),
             _row(*["---"] * 5)]
    for name, m in data["alarms"].items():
        sens = m["sensitivity"]
        fa_p, fa_l = m["false_alarm_adl_plain"], m["false_alarm_adl_lying"]
        delay = m["delay_after_lying_onset_s"]["median"]
        lines.append(_row(
            name, f"{sens['k']}/{sens['n']}", f"{fa_p['k']}/{fa_p['n']}", f"{fa_l['k']}/{fa_l['n']}",
            f"{delay:.2f}" if delay is not None else "n/a"))
    return "\n".join(lines)


def table_ros2_e2e(data: dict) -> str:
    lat = data.get("latency_ms") or {}
    lines = ["**ROS 2 end-to-end** (demo.launch.py, video_publisher -> humansense_node)", "",
             _row("Messages", "Output Hz", "Processing ms (median)", "Latency ms (median / p95 / max)"),
             _row(*["---"] * 4),
             _row(data.get("messages"), f"{data.get('output_hz', 0):.2f}" if data.get("output_hz") else "n/a",
                  f"{data.get('processing_ms_median', 0):.1f}",
                  f"{lat.get('median', 0):.1f} / {lat.get('p95', 0):.1f} / {lat.get('max', 0):.1f}")]
    return "\n".join(lines)


def table_generic(name: str, data: dict) -> str:
    def flatten(d, prefix=""):
        out = {}
        for k, v in d.items():
            key = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                out.update(flatten(v, key))
            elif isinstance(v, (int, float, str, bool)) or v is None:
                out[key] = v
        return out
    flat = flatten({k: v for k, v in data.items() if k not in ("environment",)})
    lines = [f"**{name}**", "", _row("Key", "Value"), _row("---", "---")]
    lines += [_row(k, v) for k, v in flat.items()]
    return "\n".join(lines)


def render(name: str, data: dict) -> str:
    if name.startswith("latency_"):
        return table_latency(data)
    if name.startswith("falls_"):
        return table_falls(data)
    if name == "ros2_e2e":
        return table_ros2_e2e(data)
    return table_generic(name, data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE.parent / "paper" / "tables.md"))
    a = ap.parse_args()

    files = sorted(RESULTS.glob("*.json"))
    if not files:
        print(f"no results in {RESULTS}; run some benchmarks first", file=sys.stderr)
        return 1

    sections = ["<!-- generated by benchmarks/make_tables.py from benchmarks/results/*.json -->", ""]
    for f in files:
        data = json.loads(f.read_text())
        sections.append(f"### {f.stem}\n")
        sections.append(render(f.stem, data))
        sections.append("")
    text = "\n".join(sections)

    if a.out == "-":
        print(text)
    else:
        out = Path(a.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"wrote {out} ({len(files)} result file(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
